#!/usr/bin/env python3
"""Generates tests/asm/{rv64i_alu,rv64m}.S: ALU and M-extension cases with expected
values computed here, so the assembly tests need no hand arithmetic.
Run from rv-olt/: python3 tests/asm/gen/alu_vectors.py"""

import random

M64 = (1 << 64) - 1
M32 = (1 << 32) - 1

def s64(x): x &= M64; return x - (1 << 64) if x >> 63 else x
def s32(x): x &= M32; return x - (1 << 32) if x >> 31 else x
def sx32(x): return s32(x) & M64

def div_s(a, b):
    if b == 0: return -1
    q = abs(a) // abs(b)
    return -q if (a < 0) != (b < 0) else q
def rem_s(a, b):
    if b == 0: return a
    return a - div_s(a, b) * b

OPS = {
    "add": lambda a, b: a + b,
    "sub": lambda a, b: a - b,
    "sll": lambda a, b: a << (b & 63),
    "slt": lambda a, b: int(s64(a) < s64(b)),
    "sltu": lambda a, b: int(a < b),
    "xor": lambda a, b: a ^ b,
    "srl": lambda a, b: a >> (b & 63),
    "sra": lambda a, b: s64(a) >> (b & 63),
    "or": lambda a, b: a | b,
    "and": lambda a, b: a & b,
    "addw": lambda a, b: sx32(a + b),
    "subw": lambda a, b: sx32(a - b),
    "sllw": lambda a, b: sx32(a << (b & 31)),
    "srlw": lambda a, b: sx32((a & M32) >> (b & 31)),
    "sraw": lambda a, b: sx32(s32(a) >> (b & 31)),
}
IMM = {"addi": "add", "slti": "slt", "sltiu": "sltu", "xori": "xor", "ori": "or",
       "andi": "and", "slli": "sll", "srli": "srl", "srai": "sra",
       "addiw": "addw", "slliw": "sllw", "srliw": "srlw", "sraiw": "sraw"}

M_OPS = {
    "mul": lambda a, b: a * b,
    "mulh": lambda a, b: (s64(a) * s64(b)) >> 64,
    "mulhsu": lambda a, b: (s64(a) * b) >> 64,
    "mulhu": lambda a, b: (a * b) >> 64,
    "div": lambda a, b: div_s(s64(a), s64(b)) if not (s64(a) == -(1 << 63) and s64(b) == -1) else a,
    "divu": lambda a, b: a // b if b else M64,
    "rem": lambda a, b: rem_s(s64(a), s64(b)) if not (s64(a) == -(1 << 63) and s64(b) == -1) else 0,
    "remu": lambda a, b: a % b if b else a,
    "mulw": lambda a, b: sx32(a * b),
    "divw": lambda a, b: sx32(div_s(s32(a), s32(b))) if not (s32(a) == -(1 << 31) and s32(b) == -1) else sx32(a),
    "divuw": lambda a, b: sx32((a & M32) // (b & M32)) if b & M32 else M64,
    "remw": lambda a, b: sx32(rem_s(s32(a), s32(b))) if not (s32(a) == -(1 << 31) and s32(b) == -1) else 0,
    "remuw": lambda a, b: sx32((a & M32) % (b & M32)) if b & M32 else sx32(a),
}

INTERESTING = [0, 1, 2, 3, 7, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff, 0x7fff_ffff, 0x8000_0000,
               0xffff_ffff, 0x1_0000_0000, 0x7fff_ffff_ffff_ffff, 0x8000_0000_0000_0000,
               M64, M64 - 1, 0x1234_5678_9abc_def0, 0xfedc_ba98_7654_3210, 0x8000_0000_0000_0001,
               0xffff_ffff_8000_0000, 0x0000_0000_ffff_fffe]

def h(x): return f"0x{x & M64:x}"

def cases(rng, n_random):
    pairs = [(a, b) for a in INTERESTING[::3] for b in INTERESTING[1::4]]
    pairs += [(rng.getrandbits(64), rng.getrandbits(64)) for _ in range(n_random)]
    pairs += [(rng.getrandbits(64), rng.getrandbits(6)) for _ in range(n_random)]
    return pairs

def emit(path, title, lines):
    with open(path, "w") as f:
        f.write(f"// {title}\n// Generated by tests/asm/gen/alu_vectors.py; do not edit.\n")
        f.write('#include "test.h"\nSTART\n')
        for l in lines:
            f.write("    " + l + "\n")
        f.write("END\n")

def main():
    rng = random.Random(1)
    n = 1
    lines = []
    for op, f in OPS.items():
        for a, b in cases(rng, 6)[::5]:
            lines.append(f"TEST_RR({n}, {op}, {h(f(a, b))}, {h(a)}, {h(b)})")
            n += 1
    for op, base in IMM.items():
        shift = op.startswith("s") and op not in ("slti", "sltiu")
        for a, _ in cases(rng, 4)[::7]:
            for imm in ([0, 1, 31] + ([63, 32] if not op.endswith("w") else []) if shift
                        else [0, 1, -1, 2047, -2048, 0x555]):
                lines.append(f"TEST_RI({n}, {op}, {h(OPS[base](a, imm & M64))}, {h(a)}, {imm})")
                n += 1
    emit("tests/asm/rv64i_alu.S", "RV64I register and immediate ALU operations.", lines)

    n = 1
    lines = []
    for op, f in M_OPS.items():
        prs = cases(rng, 8)[::4] + [(0x8000_0000_0000_0000, M64), (0xffff_ffff_8000_0000, M64),
                                     (5, 0), (M64, 0), (0x8000_0000, 0xffff_ffff), (7, 2), (M64 - 6, 2)]
        for a, b in prs:
            lines.append(f"TEST_RR({n}, {op}, {h(f(a, b))}, {h(a)}, {h(b)})")
            n += 1
    emit("tests/asm/rv64m.S", "RV64M multiply and divide.", lines)

main()
